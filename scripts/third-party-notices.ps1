<#
.SYNOPSIS
  Writes THIRD-PARTY-NOTICES.md: the libraries built into vesta.exe and their licences.

.DESCRIPTION
  Rust crates come from `cargo metadata` (Windows x64 target, no dev/build-only filtering beyond
  the platform); npm packages from package-lock.json (packages not marked dev).
  Run it after changing dependencies and commit the result.

.EXAMPLE
  ./scripts/third-party-notices.ps1
#>
$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$Root = Resolve-Path (Join-Path $PSScriptRoot "..")
Push-Location $Root
try {
  Push-Location src-tauri
  try {
    $meta = cargo metadata --format-version 1 --filter-platform x86_64-pc-windows-msvc | ConvertFrom-Json
  } finally { Pop-Location }
  if ($LASTEXITCODE -ne 0) { throw "cargo metadata failed" }
  $crates = $meta.packages | Where-Object { $_.name -ne "vesta" } |
    Sort-Object name, version -Unique |
    ForEach-Object { [pscustomobject]@{ Name = $_.name; Version = $_.version; License = $_.license; Url = $_.repository } }

  # -AsHashtable: the lock file has an entry with an empty name (the project itself).
  $lock = Get-Content package-lock.json -Raw | ConvertFrom-Json -AsHashtable
  $npm = foreach ($key in $lock.packages.Keys) {
    if (-not $key) { continue }                                      # the project itself
    $v = $lock.packages[$key]
    if ($v.ContainsKey("dev") -and $v.dev) { continue }              # build tools only
    $name = $key -replace "^.*node_modules/", ""
    $license = if ($v.ContainsKey("license")) { $v.license } else { "" }
    [pscustomobject]@{ Name = $name; Version = $v.version; License = $license; Url = "https://www.npmjs.com/package/$name" }
  }
  $npm = @($npm | Sort-Object Name, Version -Unique)

  $row = { param($x) "| $($x.Name) | $($x.Version) | $(if ($x.License) { $x.License } else { '(see package)' }) | $($x.Url) |" }
  $lines = @(
    "# Third-party notices",
    "",
    "Vesta is built with the libraries below. Each is the property of its authors and is used under",
    "the licence shown; the full licence text is in the package (follow the link).",
    "This file is generated by ``scripts/third-party-notices.ps1``.",
    "",
    "## JavaScript packages ($($npm.Count))",
    "",
    "| Package | Version | Licence | Source |",
    "|---|---|---|---|"
  ) + ($npm | ForEach-Object { & $row $_ }) + @(
    "",
    "## Rust crates ($(@($crates).Count))",
    "",
    "| Crate | Version | Licence | Source |",
    "|---|---|---|---|"
  ) + ($crates | ForEach-Object { & $row $_ })
  Set-Content -Path THIRD-PARTY-NOTICES.md -Value $lines -Encoding utf8
  Write-Host "THIRD-PARTY-NOTICES.md: $($npm.Count) npm packages, $(@($crates).Count) crates"
} finally {
  Pop-Location
}
